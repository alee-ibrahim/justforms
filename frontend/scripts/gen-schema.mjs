// Generates frontend artifacts from the canonical spec/form-schema.v1.json
// (itself exported from backend/app/schemas/form.py):
//   src/schema/generated/form-schema.v1.json  verbatim copy, used for zod validation
//   src/schema/generated/form.ts              TypeScript types (json-schema-to-typescript)
//   src/schema/generated/id-presets.v1.json   verbatim copy of spec/id-presets.v1.json
// Usage: pnpm gen:schema            write files
//        pnpm gen:schema --check    exit 1 if any file is stale (CI)
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = path.dirname(fileURLToPath(import.meta.url))
const specPath = path.resolve(here, '../../spec/form-schema.v1.json')
const outDir = path.resolve(here, '../src/schema/generated')

const banner = `/* GENERATED by scripts/gen-schema.mjs from spec/form-schema.v1.json. Do not edit.
 * Change backend/app/schemas/form.py, run \`uv run python -m app.schemas.export\` in backend/,
 * then \`pnpm gen:schema\` here. */`

const specText = (await readFile(specPath, 'utf8')).replaceAll('\r\n', '\n')
const spec = JSON.parse(specText)

// Pydantic titles every property ("Id", "Kind", ...), which would make json-schema-to-typescript
// emit one alias per property. Keep the `title` keyword only on named definitions. Property maps
// are walked by name so a property that is itself called "title" is kept.
const SCHEMA_MAPS = new Set(['properties', 'patternProperties', '$defs'])
const SCHEMA_LISTS = new Set(['anyOf', 'oneOf', 'allOf', 'prefixItems'])
const SCHEMA_VALUES = new Set(['items', 'additionalProperties', 'not', 'propertyNames'])

function stripTitles(schema, named) {
  if (!schema || typeof schema !== 'object' || Array.isArray(schema)) return schema
  const out = {}
  for (const [key, value] of Object.entries(schema)) {
    if (key === 'title' && !named) continue
    if (SCHEMA_MAPS.has(key)) {
      out[key] = Object.fromEntries(
        Object.entries(value).map(([name, sub]) => [name, stripTitles(sub, key === '$defs')]),
      )
    } else if (SCHEMA_LISTS.has(key)) {
      out[key] = value.map((sub) => stripTitles(sub, false))
    } else if (SCHEMA_VALUES.has(key)) {
      out[key] = stripTitles(value, false)
    } else {
      out[key] = value
    }
  }
  return out
}

const types = await compile(stripTitles(spec, true), 'JustFormsForm', {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  format: true,
  style: { semi: false, singleQuote: true, printWidth: 100 },
})

const presetsText = (await readFile(path.resolve(here, '../../spec/id-presets.v1.json'), 'utf8')).replaceAll('\r\n', '\n')

const outputs = {
  'form-schema.v1.json': specText,
  'form.ts': types,
  'id-presets.v1.json': presetsText,
}

const check = process.argv.includes('--check')
let stale = []
await mkdir(outDir, { recursive: true })
for (const [name, content] of Object.entries(outputs)) {
  const file = path.join(outDir, name)
  if (check) {
    const current = await readFile(file, 'utf8').catch(() => '')
    if (current.replaceAll('\r\n', '\n') !== content) stale.push(name)
  } else {
    await writeFile(file, content)
    console.log(`wrote ${path.relative(process.cwd(), file)}`)
  }
}
if (stale.length) {
  console.error(`stale generated files: ${stale.join(', ')}; run pnpm gen:schema`)
  process.exit(1)
}
